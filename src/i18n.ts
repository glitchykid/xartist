export type Key = keyof typeof messages;
const stored = localStorage.getItem('xartist.locale');
export let locale: Locale = locales.includes(stored as Locale)
  ? (stored as Locale)
  : locales.includes(navigator.language.slice(0, 2) as Locale)
    ? (navigator.language.slice(0, 2) as Locale)
    : 'en';
export function t(key: Key) {
  return messages[key][locales.indexOf(locale)];
}
export function setLocale(value: Locale) {
  locale = value;
  localStorage.setItem('xartist.locale', value);
  document.documentElement.lang = value;
}
